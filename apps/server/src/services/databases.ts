import { and, count, eq } from 'drizzle-orm'
import mysql from 'mysql2/promise'
import { db, schema } from '../db'
import { decrypt, encrypt, randomString } from '../lib/crypto'
import { HttpError } from '../lib/errors'

type Host = typeof schema.databaseHosts.$inferSelect

async function connect(host: Pick<Host, 'host' | 'port' | 'username' | 'password'>, encrypted = true) {
  try {
    return await mysql.createConnection({
      host: host.host,
      port: host.port,
      user: host.username,
      password: encrypted ? decrypt(host.password) : host.password,
      connectTimeout: 5000,
    })
  } catch (e) {
    throw new HttpError(
      502,
      `Could not connect to the database host: ${(e as Error).message}`,
      'database_host_unreachable',
    )
  }
}

/** Throws a readable error when the credentials cannot create users and databases. */
export async function testHost(host: Pick<Host, 'host' | 'port' | 'username' | 'password'>) {
  const conn = await connect(host, false)
  try {
    await conn.query('SELECT 1')
  } finally {
    await conn.end()
  }
}

// Identifiers are generated by us and only contain [a-z0-9_]; still escape them.
const ident = (s: string) => `\`${s.replace(/`/g, '')}\``

/** Picks a host for a server: one on the same node first, then any with free slots. */
async function pickHost(nodeId: number) {
  const hosts = await db.query.databaseHosts.findMany()
  const usage = await db
    .select({ hostId: schema.serverDatabases.databaseHostId, n: count() })
    .from(schema.serverDatabases)
    .groupBy(schema.serverDatabases.databaseHostId)
  const free = hosts.filter(
    (h) => h.maxDatabases == null || (usage.find((u) => u.hostId === h.id)?.n ?? 0) < h.maxDatabases,
  )
  const host = free.find((h) => h.nodeId === nodeId) ?? free.find((h) => h.nodeId == null) ?? free[0]
  if (!host)
    throw new HttpError(422, 'No database host is available. Please contact support.', 'no_database_host')
  return host
}

export async function createDatabase(
  server: typeof schema.servers.$inferSelect,
  name: string,
  remote: string,
) {
  const [{ n }] = (await db
    .select({ n: count() })
    .from(schema.serverDatabases)
    .where(eq(schema.serverDatabases.serverId, server.id))) as [{ n: number }]
  if (n >= server.databaseLimit) {
    throw new HttpError(
      422,
      server.databaseLimit
        ? `This server is limited to ${server.databaseLimit} databases.`
        : 'Databases are not available for this server.',
      'limit',
    )
  }
  const host = await pickHost(server.nodeId)
  const database = `s${server.id}_${name}`
  const username = `u${server.id}_${randomString(10)}`.toLowerCase()
  const password = randomString(24)
  const exists = await db.query.serverDatabases.findFirst({
    where: and(
      eq(schema.serverDatabases.databaseHostId, host.id),
      eq(schema.serverDatabases.database, database),
    ),
  })
  if (exists)
    throw new HttpError(409, 'A database with this name already exists', 'conflict', {
      name: 'Already exists',
    })

  const conn = await connect(host)
  try {
    await conn.query(`CREATE DATABASE ${ident(database)}`)
    await conn.query('CREATE USER ?@? IDENTIFIED BY ?', [username, remote, password])
    await conn.query(
      `GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP, EXECUTE, CREATE TEMPORARY TABLES, LOCK TABLES, CREATE VIEW, SHOW VIEW, CREATE ROUTINE, ALTER ROUTINE, EVENT, TRIGGER, REFERENCES ON ${ident(database)}.* TO ?@?`,
      [username, remote],
    )
    await conn.query('FLUSH PRIVILEGES')
  } catch (e) {
    // Clean up whatever was created before the failure.
    await conn.query(`DROP DATABASE IF EXISTS ${ident(database)}`).catch(() => {})
    await conn.query('DROP USER IF EXISTS ?@?', [username, remote]).catch(() => {})
    throw new HttpError(
      502,
      `The database host rejected the request: ${(e as Error).message}`,
      'database_error',
    )
  } finally {
    await conn.end()
  }
  const [row] = await db
    .insert(schema.serverDatabases)
    .values({
      serverId: server.id,
      databaseHostId: host.id,
      database,
      username,
      remote,
      password: encrypt(password),
    })
    .returning()
  return row!
}

export async function rotatePassword(row: typeof schema.serverDatabases.$inferSelect) {
  const host = (await db.query.databaseHosts.findFirst({
    where: eq(schema.databaseHosts.id, row.databaseHostId),
  }))!
  const password = randomString(24)
  const conn = await connect(host)
  try {
    await conn.query('ALTER USER ?@? IDENTIFIED BY ?', [row.username, row.remote, password])
    await conn.query('FLUSH PRIVILEGES')
  } finally {
    await conn.end()
  }
  await db
    .update(schema.serverDatabases)
    .set({ password: encrypt(password) })
    .where(eq(schema.serverDatabases.id, row.id))
}

export async function deleteDatabase(row: typeof schema.serverDatabases.$inferSelect) {
  const host = await db.query.databaseHosts.findFirst({
    where: eq(schema.databaseHosts.id, row.databaseHostId),
  })
  if (host) {
    const conn = await connect(host)
    try {
      await conn.query(`DROP DATABASE IF EXISTS ${ident(row.database)}`)
      await conn.query('DROP USER IF EXISTS ?@?', [row.username, row.remote])
    } finally {
      await conn.end()
    }
  }
  await db.delete(schema.serverDatabases).where(eq(schema.serverDatabases.id, row.id))
}

export const serializeDatabase = (
  row: typeof schema.serverDatabases.$inferSelect,
  host: Host | undefined,
  withPassword: boolean,
) => ({
  id: row.id,
  name: row.database,
  username: row.username,
  remote: row.remote,
  host: host ? { address: host.host, port: host.port } : null,
  password: withPassword ? decrypt(row.password) : undefined,
})
